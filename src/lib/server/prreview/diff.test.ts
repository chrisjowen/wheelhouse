describe('parsePatch', () => {
	const files = parsePatch(PATCH);
	const by = (p: string) => files.find((f) => f.path === p)!;

	it('reads every file, with its status and counts', () => {
		expect(files.map((f) => [f.path, f.status])).toEqual([
			['src/greet.ts', 'M'],
			['src/new.ts', 'A'],
			['package-lock.json', 'M'],
			['new/name.ts', 'R'],
			['docs/logo.png', 'M'],
			['src/api.gen.ts', 'A'],
			['src/schema.ts', 'A']
		]);
		expect(by('src/greet.ts')).toMatchObject({ additions: 3, deletions: 2 });
		expect(by('new/name.ts').oldPath).toBe('old/name.ts');
	});

	it('splits a file into hunks with their lines and new-side start', () => {
		const [a, b] = by('src/greet.ts').hunks;
		expect(a.header).toBe('@@ -1,3 +1,4 @@ export function greet');
		expect(a.newStart).toBe(1);
		expect(a.lines).toHaveLength(5);
		expect(a).toMatchObject({
			additions: 2,
			deletions: 1,
			boilerplate: null,
			path: 'src/greet.ts'
		});
		expect(b.newStart).toBe(11);
		// A blank context line is kept as a space.
		expect(by('src/new.ts').hunks[0].lines).toEqual(['+export const added = true;', '+']);
	});

	it('folds lockfiles, binaries, generated files and formatting-only hunks', () => {
		expect(by('package-lock.json').boilerplate).toBe('lockfile');
		expect(by('package-lock.json').hunks[0].boilerplate).toBe('lockfile');
		expect(by('docs/logo.png').boilerplate).toBe('binary');
		expect(by('src/api.gen.ts').boilerplate).toBe('generated');
		expect(by('src/schema.ts').boilerplate).toBe('generated');
		expect(by('src/greet.ts').boilerplate).toBeNull();
		expect(by('src/greet.ts').hunks[1].boilerplate).toBe('formatting');
	});

	it('gives hunks ids that stay the same for the same lines, and differ otherwise', () => {
		const again = parsePatch(PATCH);
		expect(again.flatMap((f) => f.hunks.map((h) => h.id))).toEqual(
			files.flatMap((f) => f.hunks.map((h) => h.id))
		);
		const ids = files.flatMap((f) => f.hunks.map((h) => h.id));
		expect(new Set(ids).size).toBe(ids.length);
		expect(ids[0]).toMatch(/^h[0-9a-f]{10}$/);
		// Line numbers moving (an earlier hunk grew) do not change the id.
		const h = by('src/greet.ts').hunks[0];
		expect(hunkId('src/greet.ts', { ...h, header: '@@ -5,3 +9,4 @@ export function greet' })).toBe(
			h.id
		);
	});

	it('numbers a repeated identical hunk in the same file', () => {
		const twice = `diff --git a/a.txt b/a.txt
--- a/a.txt
+++ b/a.txt
@@ -1 +1 @@
-x
+y
@@ -9 +9 @@
-x
+y
`;
		const [f] = parsePatch(twice);
		expect(f.hunks[1].id).toBe(`${f.hunks[0].id}-2`);
	});

	it('returns nothing for an empty diff', () => {
		expect(parsePatch('')).toEqual([]);
	});
});

describe('boilerplate rules', () => {
	it('knows lockfiles, snapshots and generated paths by name', () => {
		expect(fileBoilerplate('apps/web/pnpm-lock.yaml')).toBe('lockfile');
		expect(fileBoilerplate('go.sum')).toBe('lockfile');
		expect(fileBoilerplate('src/__snapshots__/a.test.ts.snap')).toBe('snapshot');
		expect(fileBoilerplate('dist/cli.js')).toBe('generated');
		expect(fileBoilerplate('static/app.min.js')).toBe('generated');
		expect(fileBoilerplate('src/lib/build.ts')).toBeNull();
		expect(fileBoilerplate('src/distance.ts')).toBeNull();
	});

	it('calls a hunk formatting-only when it changes only whitespace', () => {
		expect(formattingOnly(['-a  =  1', '+a = 1'])).toBe(true);
		expect(formattingOnly(['-a = 1', '+a = 2'])).toBe(false);
		expect(formattingOnly(['+a = 1'])).toBe(false);
		expect(formattingOnly([' a', '-\tb', '+    b'])).toBe(true);
	});
});
